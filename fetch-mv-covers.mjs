// TMDB posters for the MonsterVision films (see monstervision.js), written to
// mv-covers.js — separate from covers.js, which is already at GitHub's 50 MB
// warning line. Same conventions as fetch-covers.mjs: w185 covers embedded as
// data URIs under "tmdb/<id>.jpg", the poster path in VAULT_ART_HI for the
// full-res held-up view, and [year, TMDB votes] in VAULT_META. No deps:
//   TMDB_API_KEY=... node fetch-mv-covers.mjs
import fs from "node:fs";

const KEY = process.env.TMDB_API_KEY;
if (!KEY) throw new Error("set TMDB_API_KEY (v3 key or v4 read token)");
const v4 = KEY.length > 40;
async function tmdb(p, params = {}) {
  const u = new URL("https://api.themoviedb.org/3/" + p);
  for (const [k, v] of Object.entries(params)) if (v != null) u.searchParams.set(k, v);
  if (!v4) u.searchParams.set("api_key", KEY);
  for (let tries = 0; ; tries++) {
    const r = await fetch(u, { headers: v4 ? { Authorization: `Bearer ${KEY}` } : {} });
    if (r.status === 429 && tries < 5) { await new Promise(r => setTimeout(r, 1000 * (tries + 1))); continue; }
    if (!r.ok) throw new Error(`${r.status} ${p}`);
    return r.json();
  }
}
const toData = async url => "data:image/jpeg;base64," + Buffer.from(await (await fetch(url)).arrayBuffer()).toString("base64");

global.window = {};
await import("./monstervision.js");
const { FILMS, idOf } = window.VAULT_MV;
const films = new Map(Object.values(FILMS).map(([title, year]) => [idOf(title), { title, year }]));   // (the two Deliberate Stranger parts collapse to one)

const art = {}, hi = {}, meta = {}, misses = [];
for (const [id, { title, year }] of films) {
  // TV movies (Duel, The Deliberate Stranger, Horror at 37,000 Feet) aren't always "movies" on TMDB — fall back to a TV search
  let hit = (await tmdb("search/movie", { query: title, year })).results?.[0]
    || (await tmdb("search/movie", { query: title })).results?.[0]
    || (await tmdb("search/tv", { query: title, first_air_date_year: year })).results?.[0];
  if (!hit?.poster_path) { misses.push(title); continue; }
  art[`tmdb/${id}.jpg`] = await toData("https://image.tmdb.org/t/p/w185" + hit.poster_path);
  hi[`tmdb/${id}.jpg`] = hit.poster_path;
  meta[id] = [year, hit.vote_count ?? 0];
  console.log(`${title} (${year}) -> ${hit.title ?? hit.name} (${(hit.release_date ?? hit.first_air_date ?? "").slice(0, 4)})`);
}
fs.writeFileSync("mv-covers.js",
  "// generated by fetch-mv-covers.mjs — MonsterVision film covers, merged into covers.js / meta.js's globals\n" +
  `Object.assign(window.VAULT_ART ||= {}, ${JSON.stringify(art)});\n` +
  `Object.assign(window.VAULT_ART_HI ||= {}, ${JSON.stringify(hi)});\n` +
  `Object.assign(window.VAULT_META ||= {}, ${JSON.stringify(meta)});\n`);
console.log(`\n${films.size - misses.length}/${films.size} covers${misses.length ? " — no poster: " + misses.join(", ") : ""}`);
